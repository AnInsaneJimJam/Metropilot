#!/usr/bin/env bash
# Write every hosted secret to Secrets Manager from a local, git-ignored .env.hosting, never printing a value.
#   infra/scripts/put-secrets.sh [path/to/.env.hosting]
# Keys per service come from infra/secret-keys.json (the same list Terraform maps into the tasks).
# .env.hosting holds KEY=value lines; a multi-line value (PEM key, JSON evidence) can instead be given as
# KEY_FILE=path. Missing generated secrets (POSTGRES_PASSWORD, EXECUTOR/BROKER capability secrets,
# RUNTIME_WORKLOAD_SECRET) are created once and appended to .env.hosting so reruns keep the same values.
# DATABASE_URL and EXECUTOR_DATABASE_URL are composed from POSTGRES_PASSWORD and the private database name.
set -euo pipefail
export AWS_PROFILE="${AWS_PROFILE:-monad-hack}" AWS_REGION="${AWS_REGION:-us-east-1}"
root="$(cd "$(dirname "$0")/../.." && pwd)"
env_file="${1:-$root/.env.hosting}"
tf="$root/infra/terraform"
umask 077
touch "$env_file"

secrets_json="$(terraform -chdir="$tf" output -json secret_arns)"
db_host="$(terraform -chdir="$tf" output -raw database_host)"

ENV_FILE="$env_file" KEYS_FILE="$root/infra/secret-keys.json" SECRETS_JSON="$secrets_json" DB_HOST="$db_host" python3 - <<'PY'
import json, os, secrets, subprocess, sys, tempfile

env_file = os.environ["ENV_FILE"]
values, order = {}, []
with open(env_file) as f:
    for line in f:
        line = line.rstrip("\n")
        if not line or line.lstrip().startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        values[k.strip()] = v.split(" #", 1)[0].strip()
for k in list(values):
    if k.endswith("_FILE") and values[k]:
        path = os.path.expanduser(values[k])
        with open(path if os.path.isabs(path) else os.path.join(os.path.dirname(env_file), path)) as f:
            values[k[: -len("_FILE")]] = f.read().strip()

generated = []
for k in ["POSTGRES_PASSWORD", "EXECUTOR_CAPABILITY_SECRET", "BROKER_CAPABILITY_SECRET", "RUNTIME_WORKLOAD_SECRET"]:
    if not values.get(k):
        values[k] = secrets.token_hex(32)
        generated.append(k)
if generated:
    with open(env_file, "a") as f:
        f.write("\n# generated by put-secrets.sh\n" + "".join(f"{k}={values[k]}\n" for k in generated))

from urllib.parse import quote
credential = "monad:" + quote(values["POSTGRES_PASSWORD"], safe="")
values.setdefault("DATABASE_URL", "postgres://" + credential + "@" + os.environ["DB_HOST"] + ":5432/monad")
values.setdefault("EXECUTOR_DATABASE_URL", values["DATABASE_URL"])

keys = {k: v for k, v in json.load(open(os.environ["KEYS_FILE"])).items() if k != "_comment"}
arns = json.loads(os.environ["SECRETS_JSON"])
missing_required = [k for k in ["PRIVY_APP_ID", "PRIVY_VERIFICATION_KEY"] if not values.get(k)]
if missing_required:
    sys.exit(f"missing in {env_file}: {', '.join(missing_required)} (the hosted API cannot start without them)")
for service, names in keys.items():
    doc = {name: values.get(name, "") for name in names}
    with tempfile.NamedTemporaryFile("w", delete=False) as tmp:
        json.dump(doc, tmp)
        path = tmp.name
    try:
        subprocess.run(["aws", "secretsmanager", "put-secret-value", "--secret-id", arns[service], "--secret-string", f"file://{path}"],
                       check=True, stdout=subprocess.DEVNULL)
    finally:
        os.unlink(path)
    empty = [n for n in names if not doc[n]]
    print(f"{service}: wrote {len(names)} keys" + (f" (empty: {', '.join(empty)})" if empty else ""))
if generated:
    print(f"generated and saved to {env_file}: {', '.join(generated)}")
PY
